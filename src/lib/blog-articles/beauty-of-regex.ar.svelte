<p>
  واحدة من أكتر المشاكل اللي واجهتني في استخدام المواقع الحكومية هو ضعف الـ validation
  اللي بيحصل للبيانات زي الرقم القومي أو رقم الموبايل، مع إن للأسف أحيان كتير بيكون غلطة
  بسيطة في رقم واحد مثلا ممكن تلافيها بوجود validator كويس مكتوب للـ Input.
</p>
<p>
  أسهل وأقوى طريقة هي استخدام نمط فحص في attribute في الـ input اسمها `pattern`، اللي ممكن
  تكتب فيها RegEx؛ و"الريجيكس" ده تقريبا بتكتبه وكأنك بتكتب وصف طبيعي بالبلدي للنص المطلوب
  إدخاله (الرقم القومي مثلا). [وإن كان مش كل الأرقام في الرقم القومي مثلا تخضع لنمط معين،
  بس هقول لك برضه إزاي تحل المشكلة دي في الآخر.]
</p>
<p>
  الرقم القومي له صيغة معروفة؛ أولها إنه مكون من 14 رقم، وبالتالي؛ لو هنكتب له RegEx هيكون
  شكله ببساطة: <code>{`^\\d{14}$`}</code> بس في الحالة دي احنا كأننا جيبنا Hulk عشان يفتح لنا
  برطمان صلصة! 😅 كان ممكن نستخدم validator أبسط في attribute زي: maxLength و minLength ونخليهم
  الاثنين 14 وخلاص.
</p>

<p>لكن الرقم القومي مش بس له طول محدد، هو كمان ليه صيغة محددة:</p>

<ol>
  <li>أول رقم هو قرن الميلاد (قبل سنة 2000 ولا بعدها مثلا)</li>
  <li>6 أرقام لتاريخ الميلاد</li>
  <li>رقمين لمحافظة الميلاد</li>
  <li>4 أرقام تسلسلية (منها رقم لتحديد الجنس)</li>
  <li>رقم فحص (checksum)</li>
</ol>

<p>
  بالتالي، الشكل ده ممكن يتترجم [بتبسيط مُخِل] لـ RegEx تستخدمه في الفرونت والباك عشان
  تقلل فرص التلاعب. زي مثلا: <code>{`^[23]\\d{2}[01]\\d[0-3]\\d{8}$`}</code> وده ممكن تقراه:
</p>

<ul>
  <li>2 أو 3 (عشان تغطي مواليد من 1900 إلى 2099)، بعدها..</li>
  <li>رقمين (بيمثلوا سنة الميلاد، مثلا 87)، بعدهم..</li>
  <li>0 أو 1 (خانة العشرات من الشهر)، بعده..</li>
  <li>رقم (خانة الآحاد من الشهر)، بعده..</li>
  <li>رقم من 0 إلى 3 (بيمثل خانة العشرات من اليوم)، وبعده..</li>
  <li>8 أرقام (من ضمنها رقم الآحاد بتاع اليوم).</li>
</ul>

<p>
  ده نمط أحسن شوية من مجرد إنك تحصر الـ validation بتاعك بالـ 14 رقم وخلاص. بس زي ما قولت
  لك؛ ده نمط ضعيف شوية، لإنه بيسمح للمستخدم إنه يألف رقم مش صحيح، زي مثلا إنه يكتب رقم 06
  لجزء "محافظة الميلاد" وده رقم مش موجود في المواصفة. أو أسوأ كمان! إنه يسمح للمستخدم يكتب
  تاريخ ميلاد غلط؛ زي 870231 (31 فبراير سنة 1987؛ تاريخ ملوش وجود!) وده ممكن يوقع لك
  السيرفر مثلا لو بتعمل Extraction لتاريخ الميلاد من الرقم القومي من غير ما تهندل الـ case
  دي.
</p>

<p>
  وعلى ذكر الهندلة؛ من الناحية الأمنية لازم تعمل حساب هجمات ReDoS لو هتعمل الـ validation
  server-side. وده سهل جدا اليومين دول لو هتستعمل Libraries حسب الباك بتاعك، أو حتى قبل ما
  تـ Push to production ممكن extension بسيطة لـ eslint مثلا تساعدك تتفادى المشكلة قبل ما
  تحصل.
</p>

<h2>طيب، إزاي نوصل لأعلى دقة في صيغة الـ RegEx؟</h2>
<p>
  ممكن تعقد الـ RegEx زي ما انت عايز، وأنا عادة بستعمل صيغة رخمة قدر الإمكان تضمن على
  الأقل صحة 13 رقم من الـ14. وهسيب لك لينك تبص عليه براحتك في الآخر.
</p>

<h3>طيب، الرقم اللي باقي ده نعمل فيه إيه؟!</h3>
<p>
  الرقم الأخير ده هو الـ Checksum. اللي هو رقم بينتج من "هضم" باقي الأرقام. يعن الـ13 رقم
  الأولانيين بيدخلوا في خوارزمية، وبيطلعوا في الآخر الرقم الـ 14. وكل مرة هتدخل فيها نفس
  الـ 13 رقم لنفس الخوارزمية هتطلع لك نفس الرقم في الآخر. حاجة كدة شبه الـ Hash اللي ممكن
  تكون استخدمته قبل كده.
</p>

<h3>طيب إيه هي الخوارزمية دي تحديدا؟!</h3>
<p>
  ما لقيتش للأسف أي توثيق واضح للخوارزمية المستخدمة في الرقم القومي، لكن بشوية بحث عن
  أنواع تانية من الهويات والأرقام التعريفية اللي بيستخدم فيها checksum وصلت لإنها modulo
  11. ولكن بالتجربة، اتضح لي فارق بسيط عن الـ modulo 11 العادية، في إن الناتج لو كان 0،
  بيتم استبداله بـ 1 (حاجة ممكن تسبب clash كتير بس أقدر أتفهم سبب القرار التصميمي وراه من
  اللي عملوا الخوارزمية).
</p>

